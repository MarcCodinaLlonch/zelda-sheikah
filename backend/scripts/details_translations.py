def translate_location(loc):
    if not loc:
        return ""
    clean = loc.strip()
    return LOCATION_TRANSLATIONS.get(clean, clean)


def translate_drop(drop):
    if not drop:
        return ""
    clean = drop.strip().replace("\xa0", " ")
    if clean in DROP_TRANSLATIONS:
        return DROP_TRANSLATIONS[clean]
    from names_translations import ITEM_NAME_TRANSLATIONS
    if clean in ITEM_NAME_TRANSLATIONS:
        return ITEM_NAME_TRANSLATIONS[clean]
    # Si és una combinació separada per espais (com a la wiki)
    all_keys = sorted(list(DROP_TRANSLATIONS.keys()) + list(ITEM_NAME_TRANSLATIONS.keys()), key=len, reverse=True)
    found = []
    text = clean
    for k in all_keys:
        if k in text:
            trans = DROP_TRANSLATIONS.get(k, ITEM_NAME_TRANSLATIONS.get(k, k))
            found.append(trans)
            text = text.replace(k, " ")
    for w in text.split():
        if w in DROP_TRANSLATIONS:
            found.append(DROP_TRANSLATIONS[w])
        elif w in ITEM_NAME_TRANSLATIONS:
            found.append(ITEM_NAME_TRANSLATIONS[w])
    if found:
        return ", ".join(dict.fromkeys(found))
    return clean



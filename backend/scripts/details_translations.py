def translate_property(prop):
    if not prop:
        return ""
    p = prop.strip()
    if p in PROPERTY_TRANSLATIONS:
        return PROPERTY_TRANSLATIONS[p]
    m = re.match(r"^Fuse\s+(?:attack\s+power|Atk):\s*(.+)$", p, re.IGNORECASE)
    if m:
        return f"Atac de fusió: {m.group(1)}"
    m = re.match(r"^Shield\s+[Gg]uard:\s*(.+)$", p, re.IGNORECASE)
    if m:
        return f"Protecció d'escut: {m.group(1)}"
    m = re.match(r"^(?:Attack\s+power|Atk):?\s*(.+)$", p, re.IGNORECASE)
    if m:
        return f"Atac: {m.group(1)}"
    m = re.match(r"^Bow\s*(.+)$", p, re.IGNORECASE)
    if m:
        return f"Atac d'arc: {m.group(1)}"
    m = re.match(r"^Range:\s*(.+)$", p, re.IGNORECASE)
    if m:
        return f"Abast: {m.group(1)}"
    m = re.match(r"^Durability:\s*(.+)$", p, re.IGNORECASE)
    if m:
        return f"Durabilitat: {m.group(1)}"
    return p


def translate_properties(props):
    if not props:
        return []
    result = []
    i = 0
    while i < len(props):
        p = props[i].strip()
        if p == "Cooking Effects" and i + 1 < len(props):
            effect = translate_property(props[i + 1].strip())
            result.append(f"Efecte culinari: {effect}")
            i += 2
            continue
        result.append(translate_property(p))
        i += 1
    return result
